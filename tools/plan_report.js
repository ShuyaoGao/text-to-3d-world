// plan_report.js -- 用和网页完全相同的 JS 代码，把演示句子在 4 个规则档位下的理解结果和摆放统计写进 results/result.json。
//   node tools/plan_report.js            （tools/build.py 会调用它）
// README 里关于演示句子的数字都来自这个文件。种子与观看模式一致：第 i 句用 SEED + i。
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const PLAY = path.join(ROOT, 'play');
globalThis.window = globalThis;
globalThis.THREE = require(path.join(PLAY, 'vendor', 'three.min.js'));
require(path.join(PLAY, 'js', 'config.js'));
globalThis.TTW_PLANNER = require(path.join(PLAY, 'js', 'planner.js'));
globalThis.TTW_SHAPES = require(path.join(PLAY, 'js', 'shapes.js'));
const W = require(path.join(PLAY, 'js', 'world.js'));
const P = globalThis.TTW_PLANNER;
const C = globalThis.TTW_CONFIG;

const demos = C.DEMO.map((d, i) => {
  const levels = {};
  for (const L of C.LEVELS.map((l) => l.id)) {
    const w = new W.World(THREE, C.SEED + i, { overlap: C.OVERLAP_DEFAULT, tries: C.TRIES_DEFAULT });
    const r = P.plan(d.text, L, w.rng);
    const rep = w.run(r.plan);
    levels[L] = {
      plan: P.cleanPlan(r.plan),
      objects_placed: rep.placed.length,
      placement_tries: rep.tries,
      rejected: rep.rejected,
      forced: rep.fallback,
      unknown_words: r.tokens.filter((t) => t.role === 'unknown').map((t) => d.text.slice(t.s, t.e)),
    };
  }
  return { seed: C.SEED + i, text: d.text, levels };
});

const three = fs.readFileSync(path.join(PLAY, 'vendor', 'three.min.js'));
const lexWords = P.LEX.reduce((n, e) => n + e.w.length, 0);
const out = {
  _note: 'Generated by tools/plan_report.js (same JS code as play/). Do not edit by hand.',
  engine: {
    levels: C.LEVELS.map((l) => ({ id: l.id, name: l.name })),
    lexicon_entries: P.LEX.length,
    lexicon_words: lexWords,
    original_keyword_rules: P.KW.length,
    preset_object_types: Object.keys(globalThis.TTW_SHAPES.PRESETS).length,
    overlap_default: C.OVERLAP_DEFAULT,
    tries_default: C.TRIES_DEFAULT,
    seed: C.SEED,
  },
  three_js: { version: 'r' + THREE.REVISION, bytes: three.length, sha256: crypto.createHash('sha256').update(three).digest('hex') },
  demos,
};
fs.mkdirSync(path.join(ROOT, 'results'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'results', 'result.json'), JSON.stringify(out, null, 2) + '\n', 'utf8');
console.log('wrote results/result.json:', demos.length, 'demo sentences x', C.LEVELS.length, 'levels');
