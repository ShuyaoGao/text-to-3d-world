# -*- coding: utf-8 -*-
"""Open play/index.html in the locally installed Edge / Chrome (headless), run the page's built-in self-test
at 1920x1080 and 1366x768, write results/browser_check.json, optionally take the README screenshots.

    python -m tools.browser_check                 # self-test, both window sizes -> results/browser_check.json
    python -m tools.browser_check --shots docs/img  # also write screenshots

Only an already installed Edge / Chrome is used (no browser downloads). Two drivers:

  1. Playwright (preferred, `pip install playwright`; it uses the installed Edge through channel="msedge",
     nothing is downloaded). The machine-wide Edge lock and free-memory guard from tools/mobile_check.py are
     used, so that only one Edge runs on the machine at a time. WebGL runs on the software renderer
     (SwiftShader) in headless mode.
  2. Fallback (--raw, or when Playwright is missing): launch the browser executable directly with
     --headless --dump-dom / --screenshot in a temporary --user-data-dir; only the processes started here are
     terminated. Recent Edge builds exit immediately when started this way, so prefer Playwright.

The self-test (play/js/app.js `selftest()`) drives every mode (watch / build / practice, rule levels,
undo / delete / random scene / clear, big screen, help, exit) and asserts no JS errors and no horizontal
overflow. Phone sizes are checked separately by tools/mobile_check_ttw.py.
"""

import argparse
import contextlib
import ctypes
import datetime as _dt
import html
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "play" / "index.html"
RESULT = ROOT / "results" / "browser_check.json"
SIZES = [(1920, 1080), (1366, 768)]
CANDIDATES = [
    r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
    r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
    r"C:\Program Files\Google\Chrome\Application\chrome.exe",
    "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
]
SWIFTSHADER = ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"]
SHOTS = [
    ("watch_1920x1080.png", (1920, 1080), "shot=watch"),
    ("build_1366x768.png", (1366, 768), "shot=build&q=%E8%A5%BF%E5%8D%97%E4%B8%80%E7%89%87%E8%8A%B1%E6%B5%B7%EF%BC%8C%E8%8A%B1%E4%B8%9B%E6%97%81%E8%BE%B9%E4%B8%89%E5%9D%97%E7%9F%B3%E5%A4%B4%EF%BC%8C%E4%B8%9C%E5%8C%97%E4%B8%80%E5%BA%A7%E7%BA%A2%E8%89%B2%E7%9A%84%E5%A1%94"),
    ("practice_big_1920x1080.png", (1920, 1080), "shot=practice&big=1"),
]


# ----------------------------------------------------------------------------- shared helpers
def find_browser():
    env = os.environ.get("BROWSER_EXE")
    if env and Path(env).exists():
        return env
    for c in CANDIDATES:
        if Path(c).exists():
            return c
    for name in ("msedge", "microsoft-edge", "google-chrome", "chromium", "chrome"):
        p = shutil.which(name)
        if p:
            return p
    return None


def free_mb():
    if sys.platform != "win32":
        return None

    class MS(ctypes.Structure):
        _fields_ = [("dwLength", ctypes.c_ulong), ("dwMemoryLoad", ctypes.c_ulong),
                    ("ullTotalPhys", ctypes.c_ulonglong), ("ullAvailPhys", ctypes.c_ulonglong),
                    ("ullTotalPageFile", ctypes.c_ulonglong), ("ullAvailPageFile", ctypes.c_ulonglong),
                    ("ullTotalVirtual", ctypes.c_ulonglong), ("ullAvailVirtual", ctypes.c_ulonglong),
                    ("ullAvailExtendedVirtual", ctypes.c_ulonglong)]
    m = MS()
    m.dwLength = ctypes.sizeof(MS)
    ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(m))
    return m.ullAvailPhys // (1024 * 1024)


def wait_for_memory(min_mb, max_wait_s):
    t0 = time.time()
    while True:
        f = free_mb()
        if f is None or f >= min_mb:
            return f
        if time.time() - t0 > max_wait_s:
            return f
        print(f"  free memory {f} MB < {min_mb} MB, waiting...", flush=True)
        time.sleep(15)


def shared_lock():
    """The machine-wide Edge lock from tools/mobile_check.py (one Edge at a time on this machine)."""
    try:
        sys.path.insert(0, str(ROOT))
        from tools.mobile_check import EdgeLock
    except ImportError:
        return None
    return EdgeLock()


def good(r):
    return bool(r.get("ok")) and not r.get("errors")


def write_result(results, info, shots):
    out = {
        "_note": "Generated by tools/browser_check.py from the page's built-in self-test (play/index.html?selftest=1): "
                 "every mode, the 4 rule levels, undo / delete / random scene / clear, big-screen mode, help and exit; "
                 "'checks' is the number of assertions, 'failed' the ones that did not hold, 'errors' the JS errors.",
        "date": _dt.date.today().isoformat(),
        "browser": info,
        "sizes": {k: {"ok": good(v), "webgl": v.get("webgl"), "checks": len(v.get("checks", [])),
                      "failed": [c for c in v.get("checks", []) if not c[1]], "errors": v.get("errors", [])} for k, v in results.items()},
        "screenshots": shots,
    }
    RESULT.parent.mkdir(parents=True, exist_ok=True)
    RESULT.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    return RESULT


# ----------------------------------------------------------------------------- driver 1: Playwright
def playwright_available():
    try:
        import playwright.sync_api  # noqa: F401
        return True
    except ImportError:
        return False


def run_playwright(do_shots, shots_dir, results):
    """Returns (ok, browser_info, shot_names) or None when no Edge / Chrome channel is available."""
    from playwright.sync_api import sync_playwright

    ok, shots = True, []
    with sync_playwright() as p:
        browser, channel = None, None
        for channel in ("msedge", "chrome"):
            try:
                browser = p.chromium.launch(channel=channel, headless=True, args=SWIFTSHADER)
                print("browser: playwright channel", channel, browser.version, flush=True)
                break
            except Exception as e:  # channel not installed
                print(f"  playwright channel {channel} unavailable: {str(e).splitlines()[0][:120]}")
        if browser is None:
            return None
        info = {"name": {"msedge": "Microsoft Edge", "chrome": "Google Chrome"}[channel], "channel": channel, "version": browser.version,
                "driver": "playwright", "headless": True, "webgl": "swiftshader"}

        def selftest(size, timeout=120000):
            ctx = browser.new_context(viewport={"width": size[0], "height": size[1]}, locale="zh-CN")
            page = ctx.new_page()
            errs = []
            page.on("pageerror", lambda e: errs.append(f"pageerror: {e}"))
            page.goto(INDEX.as_uri() + "?selftest=1")
            try:
                page.wait_for_function("(() => { const e = document.getElementById('selftest'); return e && e.textContent.length > 0; })()",
                                       timeout=timeout)
                r = json.loads(page.evaluate("document.getElementById('selftest').textContent"))
            except Exception as e:
                r = {"ok": False, "errors": [f"self-test did not finish: {e!r}"[:300]]}
            if errs:
                r.setdefault("errors", []).extend(errs)
            ctx.close()
            return r

        try:
            for size in SIZES:
                r = selftest(size)
                results[f"{size[0]}x{size[1]}"] = r
                ok = ok and good(r)
                bad = [c for c in r.get("checks", []) if not c[1]]
                print(f"[{size[0]}x{size[1]}] {'PASS' if good(r) else 'FAIL'}: {len(r.get('checks', []))} checks, webgl={r.get('webgl')}, "
                      f"failed={json.dumps(bad, ensure_ascii=False)}, errors={json.dumps(r.get('errors', []), ensure_ascii=False)[:800]}", flush=True)
            if do_shots:
                for name, size, q in SHOTS:
                    ctx = browser.new_context(viewport={"width": size[0], "height": size[1]}, locale="zh-CN")
                    page = ctx.new_page()
                    page.goto(INDEX.as_uri() + "?" + q + "&nohelp=1")
                    page.wait_for_function("window.TTW_APP && window.TTW_APP.ready", timeout=120000)
                    # watch mode: wait until the demo sentence has been typed and built, so the world is not empty
                    page.wait_for_function("window.TTW_APP.st.mode !== 'watch' || window.TTW_APP.watchPhase() === 'hold'", timeout=60000)
                    page.wait_for_timeout(1200)
                    out = shots_dir / name
                    page.screenshot(path=str(out), full_page=False)
                    ctx.close()
                    done = out.exists() and out.stat().st_size > 0
                    print(f"  screenshot {name}: {'ok' if done else 'FAILED'}", flush=True)
                    ok = ok and done
                    shots.append(name)
        finally:
            browser.close()
    return ok, info, shots


# ----------------------------------------------------------------------------- driver 2: raw executable
def run_browser(exe, url, size, extra, timeout=120):
    prof = tempfile.mkdtemp(prefix="ttw_edge_")
    args = [exe, "--headless=new", "--use-angle=swiftshader", "--enable-unsafe-swiftshader",
            "--no-first-run", "--no-default-browser-check",
            "--disable-extensions", "--disable-sync", "--mute-audio", "--hide-scrollbars",
            f"--user-data-dir={prof}", f"--window-size={size[0]},{size[1]}"] + extra + [url]
    p = subprocess.Popen(args, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    try:
        out, _ = p.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        if sys.platform == "win32":
            subprocess.run(["taskkill", "/T", "/F", "/PID", str(p.pid)], capture_output=True)
        else:
            p.kill()
        out, _ = p.communicate()
        raise RuntimeError(f"browser timed out after {timeout}s")
    finally:
        time.sleep(0.5)
        shutil.rmtree(prof, ignore_errors=True)
    return out.decode("utf-8", "replace")


def selftest_raw(exe, size):
    url = INDEX.as_uri() + "?selftest=1"
    dom = run_browser(exe, url, size, ["--virtual-time-budget=20000", "--dump-dom"])
    m = re.search(r'<pre id="selftest"[^>]*>(.*?)</pre>', dom, re.S)
    if not m or not m.group(1).strip():
        return {"ok": False, "errors": ["self-test result not found in DOM"], "title": re.findall(r"<title>(.*?)</title>", dom)}
    return json.loads(html.unescape(m.group(1)))


def screenshot_raw(exe, size, query, path):
    url = INDEX.as_uri() + "?" + query
    path = Path(path).resolve()
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        path.unlink()
    run_browser(exe, url, size, ["--virtual-time-budget=5000", f"--screenshot={path}"])
    return path.exists() and path.stat().st_size > 0


def browser_version(exe):
    if sys.platform == "win32":
        try:
            r = subprocess.run(["powershell", "-NoProfile", "-Command", f"(Get-Item '{exe}').VersionInfo.ProductVersion"],
                               capture_output=True, text=True, timeout=20)
            return r.stdout.strip() or None
        except Exception:
            return None
    return None


def run_raw(exe, do_shots, shots_dir, results, min_free_mb, max_wait):
    print("browser:", exe)
    ok, shots = True, []
    for size in SIZES:
        f = wait_for_memory(min_free_mb, max_wait)
        print(f"[{size[0]}x{size[1]}] free memory: {f} MB", flush=True)
        r = selftest_raw(exe, size)
        results[f"{size[0]}x{size[1]}"] = r
        ok = ok and good(r)
        bad = [c for c in r.get("checks", []) if not c[1]]
        print(f"  {'PASS' if good(r) else 'FAIL'}: {len(r.get('checks', []))} checks, webgl={r.get('webgl')}, "
              f"failed={json.dumps(bad, ensure_ascii=False)}, errors={json.dumps(r.get('errors', []), ensure_ascii=False)[:800]}", flush=True)
    if do_shots:
        for name, size, q in SHOTS:
            wait_for_memory(min_free_mb, max_wait)
            done = screenshot_raw(exe, size, q + "&nohelp=1", shots_dir / name)
            print(f"  screenshot {name}: {'ok' if done else 'FAILED'}", flush=True)
            ok = ok and done
            shots.append(name)
    return ok, {"name": Path(exe).stem, "version": browser_version(exe), "driver": "exe", "headless": True, "webgl": "swiftshader"}, shots


# ----------------------------------------------------------------------------- main
def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--shots", help="directory for screenshots")
    ap.add_argument("--no-result", action="store_true", help="do not rewrite results/browser_check.json")
    ap.add_argument("--min-free-mb", type=int, default=1000)
    ap.add_argument("--max-wait", type=int, default=600, help="seconds to wait for free memory")
    ap.add_argument("--raw", action="store_true", help="skip Playwright, launch the browser executable directly")
    args = ap.parse_args(argv)
    shots_dir = None
    if args.shots:
        shots_dir = Path(args.shots)
        if not shots_dir.is_absolute():
            shots_dir = ROOT / shots_dir
        shots_dir.mkdir(parents=True, exist_ok=True)
    results = {}
    lock = shared_lock()
    with (lock if lock is not None else contextlib.nullcontext()):
        if lock is None:
            wait_for_memory(args.min_free_mb, args.max_wait)
        res = None
        if not args.raw and playwright_available():
            res = run_playwright(bool(shots_dir), shots_dir, results)
        if res is None:
            exe = find_browser()
            if not exe:
                print("no Edge / Chrome found: browser check NOT run")
                return 2
            res = run_raw(exe, bool(shots_dir), shots_dir, results, args.min_free_mb, args.max_wait)
    ok, info, shots = res
    if not args.no_result and results:
        print("wrote", write_result(results, info, shots).relative_to(ROOT).as_posix())
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
