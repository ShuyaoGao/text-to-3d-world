# -*- coding: utf-8 -*-
"""One command to build the static page (play/), the full version (app/) and the release zip.

    python -m tools.build              # credits.js + app/index_full.html + results/result.json + checks
    python -m tools.build --release    # ... and release/<repo>-v<version>.zip (play/ + the root index.html)

play/ is plain HTML + JS: it runs from file:// (double-click index.html) without Python or a network.
results/result.json is produced by `node tools/plan_report.js` (needs Node.js); without Node the
existing file is kept.
"""

import argparse
import json
import re
import shutil
import subprocess
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLAY = ROOT / "play"
RELEASE = ROOT / "release"
ZIP_LIMIT = 15 * 1024 * 1024
THREE_SRC = 'src="vendor/three.min.js"'
THREE_FULL = 'src="../play/vendor/three.min.js"'

# play/ must work from file:// with no network: these patterns are not allowed in our own code
FORBIDDEN = [
    (r'type\s*=\s*["\']module["\']', "<script type=module>"),
    (r"\bfetch\s*\(", "fetch()"),
    (r"XMLHttpRequest", "XMLHttpRequest"),
    (r"serviceWorker", "service worker"),
    (r"\bimport\s*\(", "dynamic import()"),
    (r"https?://(?!www\.w3\.org)", "absolute URL (CDN / API)"),
]


def load_credits():
    for p in (ROOT / "credits.json", ROOT / "tools" / "credits.default.json"):
        if p.exists():
            return json.loads(p.read_text(encoding="utf-8"))
    raise FileNotFoundError("credits.json not found")


def write_credits_js(credits):
    keep = {k: v for k, v in credits.items() if not k.startswith("_")}
    js = ("/* Generated by tools/build.py from credits.json -- edit credits.json, then rebuild. */\n"
          "window.CREDITS = " + json.dumps(keep, ensure_ascii=False, indent=2) + ";\n")
    out = PLAY / "js" / "credits.js"
    out.write_text(js, encoding="utf-8", newline="\n")
    return out


def write_full_version():
    """app/index_full.html = the original page (local model service / online API), with the
    three.js path pointed at play/vendor so the file is not duplicated. The original index.html
    is not changed."""
    src = ROOT / "index.html"
    if not src.exists():          # inside the published repository the original is not shipped
        return None
    html = src.read_text(encoding="utf-8")
    if 'http-equiv="refresh"' in html:   # the published repository's root index.html is only the redirect page
        return None
    if THREE_SRC not in html:
        raise SystemExit("index.html: three.js <script> tag not found")
    html = html.replace(THREE_SRC, THREE_FULL, 1)
    note = ("<!-- 完整版（原版页面）：可以连接本机的大模型服务或在线的 OpenAI 兼容接口，让大语言模型理解任意描述。\n"
            "     它会联网 / 连本机端口，所以不放进 play/；离线版见 ../play/index.html。用法见 README「完整版」一节。 -->\n")
    html = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + note, 1)
    out = ROOT / "app" / "index_full.html"
    out.parent.mkdir(exist_ok=True)
    out.write_text(html, encoding="utf-8", newline="\n")
    return out


def check_play():
    problems = []
    for p in sorted(PLAY.rglob("*")):
        if not p.is_file() or p.suffix not in {".html", ".js", ".css"} or "vendor" in p.parts:
            continue
        text = p.read_text(encoding="utf-8")
        for pat, name in FORBIDDEN:
            for m in re.finditer(pat, text):
                problems.append(f"{p.relative_to(ROOT).as_posix()}: {name}: {m.group(0)!r}")
    return problems


def run_plan_report():
    node = shutil.which("node")
    if not node:
        print("Node.js not found: keeping the existing results/result.json")
        return False
    r = subprocess.run([node, str(ROOT / "tools" / "plan_report.js")], cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
    print(r.stdout.strip())
    if r.returncode:
        raise SystemExit(r.stderr)
    return True


def root_index_html(credits):
    """The repository-root index.html (meta refresh to play/index.html) that also goes into the zip, so that
    "unzip, then double-click index.html" works. Rendered from the template (tools/templates/ inside the published
    repository, tools/publish_templates/ inside the internal one); the internal root index.html is the original page."""
    for p in (ROOT / "tools" / "templates" / "index.html.tmpl", ROOT / "tools" / "publish_templates" / "index.html.tmpl"):
        if p.exists():
            text = p.read_text(encoding="utf-8")
            return re.sub(r"\{\{([A-Z0-9_]+)\}\}", lambda m: str(credits.get(m.group(1), m.group(0))), text).encode("utf-8")
    return None


def make_zip(credits):
    """release/<repo>-v<version>.zip = play/ + the root index.html (nothing else)."""
    RELEASE.mkdir(exist_ok=True)
    name = f"{credits.get('REPO_NAME', 'text-to-3d-world')}-v{credits.get('VERSION', '1.0')}.zip"
    out = RELEASE / name
    entries = [("play/" + p.relative_to(PLAY).as_posix(), p.read_bytes()) for p in sorted(PLAY.rglob("*")) if p.is_file()]
    idx = root_index_html(credits)
    if idx:
        entries.insert(0, ("index.html", idx))
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for arc, data in entries:
            info = zipfile.ZipInfo(arc, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
    size = out.stat().st_size
    if size > ZIP_LIMIT:
        raise SystemExit(f"release zip is {size} bytes > 15 MB limit")
    return out, size, len(entries)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--release", action="store_true", help="also build the release zip")
    ap.add_argument("--skip-report", action="store_true", help="do not regenerate results/result.json")
    args = ap.parse_args(argv)

    credits = load_credits()
    print("wrote", write_credits_js(credits).relative_to(ROOT).as_posix())
    full = write_full_version()
    if full:
        print("wrote", full.relative_to(ROOT).as_posix())
    if not args.skip_report:
        run_plan_report()
    problems = check_play()
    if problems:
        raise SystemExit("play/ is not offline-safe:\n  " + "\n  ".join(problems))
    total = sum(p.stat().st_size for p in PLAY.rglob("*") if p.is_file())
    print(f"play/ = {total} bytes, offline check passed")
    if args.release:
        out, size, n = make_zip(credits)
        print(f"wrote {out.relative_to(ROOT).as_posix()}: {n} files, {size} bytes")


if __name__ == "__main__":
    main()
